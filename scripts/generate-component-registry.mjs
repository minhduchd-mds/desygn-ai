import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const barrelPath = join(root, "packages/ui/src/primitives/index.ts");
const storiesDir = join(root, "packages/ui/stories");
const outputJson = join(root, "packages/ui/registry/component-registry.json");
const outputMd = join(root, "packages/ui/registry/component-registry.md");

function toPosix(path) {
  return path.replaceAll("\\", "/");
}

function rel(path) {
  return toPosix(relative(root, path));
}

function discoverComponents() {
  const barrel = readFileSync(barrelPath, "utf8");
  // Public primitives follow `export { Component, type ComponentProps ... }`.
  // Requiring the matching Props export avoids treating uppercase helper constants
  // (for example focus-trap selectors) as components.
  const matches = [
    ...barrel.matchAll(
      /export\s*\{\s*([A-Z][A-Za-z0-9]*),\s*type\s+\1Props[^}]*\}\s*from\s*["']\.\/([A-Za-z0-9-]+)\.js["'];?/g,
    ),
  ];

  const seen = new Set();
  return matches
    .map((match) => ({ name: match[1], moduleName: match[2] }))
    .filter(({ name }) => {
      if (seen.has(name)) return false;
      seen.add(name);
      return true;
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

function buildRegistry() {
  const components = discoverComponents().map(({ name, moduleName }) => {
    const source = join(root, `packages/ui/src/primitives/${moduleName}.tsx`);
    const story = join(storiesDir, `${name}.stories.tsx`);
    const sourceExists = existsSync(source);
    if (!sourceExists) {
      throw new Error(`Registry source missing for ${name}: ${rel(source)}`);
    }

    return {
      id: `desygn.${name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()}`,
      name,
      package: "@desygn/ui",
      import: "@desygn/ui",
      source: rel(source),
      story: existsSync(story) ? rel(story) : null,
      hasStory: existsSync(story),
      contract: {
        accessibilityRequired: true,
        semanticTokensRequired: true,
        visualVerificationRequired: true,
      },
    };
  });

  return {
    schemaVersion: 1,
    generatedFrom: rel(barrelPath),
    package: "@desygn/ui",
    componentCount: components.length,
    components,
  };
}

function renderJson(registry) {
  return `${JSON.stringify(registry, null, 2)}\n`;
}

function renderMarkdown(registry) {
  const rows = registry.components
    .map(
      (component) =>
        `| \`${component.id}\` | ${component.name} | \`${component.source}\` | ${component.hasStory ? `\`${component.story}\`` : "MISSING"} |`,
    )
    .join("\n");

  return `# @desygn/ui Component Registry\n\n> AUTO-GENERATED by \`npm run registry:generate\`. Do not edit by hand.\n\nSource of truth: \`${registry.generatedFrom}\`\n\nComponents: **${registry.componentCount}**\n\n| ID | Component | Source | Storybook |\n|---|---|---|---|\n${rows}\n\n## Contract\n\nEvery registered primitive is expected to use semantic tokens, preserve accessibility behavior, and participate in visual verification. A missing story is a registry defect and should be fixed rather than documented away.\n`;
}

function checkFile(path, expected) {
  if (!existsSync(path)) return false;
  return readFileSync(path, "utf8") === expected;
}

const registry = buildRegistry();
const json = renderJson(registry);
const markdown = renderMarkdown(registry);
const check = process.argv.includes("--check");

if (check) {
  const stale = [];
  if (!checkFile(outputJson, json)) stale.push(rel(outputJson));
  if (!checkFile(outputMd, markdown)) stale.push(rel(outputMd));
  if (registry.components.some((component) => !component.hasStory)) {
    stale.push("one or more registered components are missing Storybook stories");
  }

  if (stale.length > 0) {
    console.error("Component registry check failed:");
    for (const item of stale) console.error(`- ${item}`);
    console.error("Run: npm run registry:generate");
    process.exit(1);
  }

  console.log(`Component registry is current (${registry.componentCount} components).`);
} else {
  writeFileSync(outputJson, json);
  writeFileSync(outputMd, markdown);
  console.log(`Generated component registry for ${registry.componentCount} components.`);
}
